import assert from 'node:assert/strict';
import {chromium} from 'playwright';

const browser=await chromium.launch({channel:'chrome',headless:true});
const base=(process.env.VIRENA_QA_URL||'http://127.0.0.1:5174/')+'?tab=store&page=checkout&checkoutScenario=';
const screenshots=process.env.VIRENA_QA_SCREENSHOTS;
try {
 for(const [width,fixture,cards] of [[1440,'recipient-ready',1],[390,'cells-two',2],[320,'cells-three',3]]){
  const page=await browser.newPage({viewport:{width,height:950},reducedMotion:'reduce'});
  try{
   await page.goto(base+fixture);
   const buyer=page.locator('.checkout-buyer-panel'),payer=buyer.locator('.checkout-payer-options');
   const self=buyer.getByRole('tab',{name:'Себе',exact:true}),other=buyer.getByRole('tab',{name:'На другой аккаунт',exact:true});
   const input=buyer.getByRole('textbox',{name:'ID ячейки получателя'});
   const pending=buyer.getByRole('status',{name:'Ищем ячейку'});
   const field=buyer.locator('.checkout-recipient-lookup .real-field');
   const panel=buyer.getByRole('tabpanel');
   const equalWidths=async()=>assert.ok(Math.abs((await field.boundingBox()).width-(await panel.boundingBox()).width)<=1);
   const found=buyer.getByRole('radio',{name:/anna\.volkova/});
   const summary=page.getByRole('complementary',{name:'Итоги оформления'});
   const choose=id=>payer.getByRole('radio',{name:new RegExp(id)});
   const shot=async(name)=>{if(screenshots)await buyer.screenshot({path:`${screenshots}/${name}-${width}.png`});};
   await buyer.getByText('alexandra@example.com',{exact:true}).waitFor();
   await buyer.getByText('+7 999 123-45-67',{exact:true}).waitFor();
   assert.equal(await self.getAttribute('aria-selected'),'true');
   assert.equal(await payer.getByRole('radio').count(),cards);
   assert.equal(await payer.locator('legend').evaluate(el=>getComputedStyle(el,'::before').maskImage),'none');
   assert.ok(await choose('VR-100024').isChecked());
   assert.equal(await buyer.getByRole('combobox').count(),0);
   assert.equal(await buyer.evaluate(el=>el.scrollWidth<=el.clientWidth),true);
   await shot('self');
   const payerId=cards>1?'VR-100026':'VR-100024';
   if(cards>1)await choose(payerId).check();
   assert.equal(await summary.getByText(/Заказ на/).count(),0);
   await page.locator('.has-page-skeleton').waitFor({state:'detached'});
   await self.focus();
   await self.and(page.locator(':focus')).waitFor();
   await page.keyboard.press('ArrowRight');
   await input.waitFor();
   await equalWidths();
   assert.equal(await buyer.getByRole('group',{name:'Ячейка плательщика'}).count(),0);
   await shot('other-idle');
   assert.equal(await other.getAttribute('aria-selected'),'true');
   assert.equal(await buyer.getByText('alexandra@example.com',{exact:true}).count(),0);
   assert.equal(await buyer.getByRole('button',{name:'Найти',exact:true}).count(),0);
   assert.equal(await input.getAttribute('inputmode'),'numeric');
   await input.fill('VR-10008');
   assert.equal(await pending.count(),0);
   await input.fill('VR-100082');
   await pending.waitFor();
   await equalWidths();
   await shot('other-pending');
   await input.fill('VR-10008');
   await page.waitForTimeout(420);
   assert.equal(await buyer.getByRole('alert').count(),0);
   await input.fill('VR-100082');
   await buyer.getByRole('alert').getByText(/Ячейка с таким ID не найдена/).waitFor();
   await equalWidths();
   await shot('other-error');
   await input.fill(payerId);
   await buyer.getByRole('alert').getByText(/Это ваша ячейка/).waitFor();
   await input.fill('VR-100081');
   await pending.waitFor();
   assert.equal(await found.count(),0);
   await found.waitFor();
   assert.equal(await input.inputValue(),'100081');
   await buyer.getByText('anna.volkova',{exact:true}).waitFor();
   await buyer.getByText('VR-100081',{exact:true}).waitFor();
   assert.ok(!(await buyer.innerText()).includes('Анна Волкова'));
   await input.fill('100081');
   assert.equal(await pending.count(),0);
   assert.equal(await buyer.evaluate(el=>el.scrollWidth<=el.clientWidth),true);
   await equalWidths();
   await shot('other-found');
   await found.press('Space');
   assert.ok(await found.isChecked());
   assert.equal(await summary.getByText(/Заказ на/).count(),0);
   await equalWidths();
   assert.equal(await input.evaluate(el=>el.readOnly),true);
   const payerRegion=buyer.getByRole('group',{name:'Ячейка плательщика'});
   await payerRegion.waitFor();
   assert.equal(await buyer.getByText('Оплачиваете вы',{exact:true}).count(),0);
   if(cards===1)await payerRegion.getByText(new RegExp(payerId)).waitFor();
   else assert.ok(await choose(payerId).isChecked());
   await shot('other-confirmed');
   await buyer.getByRole('button',{name:'Изменить получателя'}).click();
   await input.and(page.locator(':focus')).waitFor();
   assert.equal(await input.inputValue(),'100081');
   assert.ok(await input.isEditable());
   assert.equal(await pending.count(),0);
   await found.waitFor();
   assert.equal(await buyer.getByRole('group',{name:'Ячейка плательщика'}).count(),0);
   await equalWidths();
   await shot('other-edit');
   await found.click();
   const apply=page.locator('.checkout-stage-actions').getByRole('button',{name:'Применить',exact:true});
   await apply.click();
   await summary.getByText(/Заказ на anna\.volkova/).waitFor();
   await summary.getByText(new RegExp('Оплачивает.*'+payerId)).waitFor();
   if(cards===2){
    await page.getByRole('tab',{name:'Забрать в шоу-руме'}).click();
    await page.getByRole('radio',{name:/Садовая/}).click();
    await page.getByRole('textbox',{name:'Имя и фамилия получателя'}).fill('Анна Волкова');
    await page.getByRole('textbox',{name:'Телефон получателя'}).fill('9991234567');
    await apply.click();
    await page.getByRole('radio',{name:/Банковская карта/}).check();
    await page.getByRole('button',{name:'Перейти к оплате',exact:true}).click();
    const payment=page.locator('.checkout-pay-card');
    await payment.getByRole('heading',{name:'Оплата банковской картой'}).waitFor();
    await payment.getByText(new RegExp('VR-100081.*Оплачивает.*'+payerId)).waitFor();
    assert.ok(await payment.getByRole('textbox',{name:'Номер карты',exact:true}).isEditable());
   }
   console.log(`PASS ${width} px, ${cards} owned cells: preselection, keyboard tabs, partial/missing/own/stale lookup, recipient confirmation and payer.`);
  }finally{await page.close();}
 }
 const guest=await browser.newPage({viewport:{width:390,height:850}});
 await guest.goto(base+'recipient-ready&visitor=guest');
 await guest.getByRole('heading',{name:'Войдите, чтобы оформить заказ'}).waitFor();
 assert.equal(await guest.getByRole('tab',{name:'Себе',exact:true}).count(),0);
 assert.equal(await guest.getByRole('button',{name:'Перейти к оплате',exact:true}).count(),0);
 await guest.close();
 console.log('PASS guest verification gate.');
}finally{await browser.close();}
